import { sql } from "drizzle-orm";
import { boolean, check, doublePrecision, foreignKey, index, integer, jsonb, pgPolicy, pgTable, text, timestamp, unique, uniqueIndex, uuid, varchar } from "drizzle-orm/pg-core";
import { cases, institutionMemberships, institutions, observedContent, officialReferenceVersions } from "./index";

const time = (name: string) => timestamp(name, { withTimezone: true });
const policy = (name: string) => pgPolicy(name, {
  for: "all",
  using: sql`institution_id = NULLIF(current_setting('marjea.tenant_id', true), '')::uuid`,
  withCheck: sql`institution_id = NULLIF(current_setting('marjea.tenant_id', true), '')::uuid`,
});

export const demoScenarios = pgTable("marjea_demo_scenarios", {
  id: uuid("id").primaryKey().defaultRandom(),
  institutionId: uuid("institution_id").notNull().references(() => institutions.id),
  scenarioKey: varchar("scenario_key", { length: 80 }).notNull(),
  generation: integer("generation").notNull().default(1),
  baseInputIds: jsonb("base_input_ids").notNull().default(sql`'{}'::jsonb`),
  createdBy: varchar("created_by", { length: 255 }).notNull(),
  resetBy: varchar("reset_by", { length: 255 }),
  resetAt: time("reset_at"),
  createdAt: time("created_at").notNull().defaultNow(),
  updatedAt: time("updated_at").notNull().defaultNow(),
}, (t) => [
  unique("marjea_demo_tenant_id_unique").on(t.institutionId, t.id),
  unique("marjea_demo_tenant_key_unique").on(t.institutionId, t.scenarioKey),
  check("marjea_demo_generation_check", sql`${t.generation} >= 1`),
  foreignKey({ name: "marjea_demo_creator_fk", columns: [t.institutionId, t.createdBy], foreignColumns: [institutionMemberships.tenantId, institutionMemberships.clerkUserId] }),
  foreignKey({ name: "marjea_demo_resetter_fk", columns: [t.institutionId, t.resetBy], foreignColumns: [institutionMemberships.tenantId, institutionMemberships.clerkUserId] }),
  policy("marjea_demo_tenant_policy"),
]).enableRLS();

// Fresh column instances per table. Older generations remain valid after reset.
export const demoColumns = () => ({
  demoScenarioId: uuid("demo_scenario_id"),
  demoGeneration: integer("demo_generation"),
});

export const semanticAnalyses = pgTable("marjea_semantic_analyses", {
  id: uuid("id").primaryKey().defaultRandom(),
  institutionId: uuid("institution_id").notNull().references(() => institutions.id),
  officialReferenceId: uuid("official_reference_id").notNull(),
  officialReferenceVersionNumber: integer("official_reference_version_number").notNull(),
  observedContentId: uuid("observed_content_id").notNull(),
  caseId: uuid("case_id"),
  requestedBy: varchar("requested_by", { length: 255 }).notNull(),
  analysisStatus: varchar("analysis_status", { length: 40 }).notNull().default("queued"),
  engineVersion: varchar("engine_version", { length: 160 }).notNull(),
  model: varchar("model", { length: 100 }).notNull(),
  schemaVersion: varchar("schema_version", { length: 80 }).notNull(),
  promptVersion: varchar("prompt_version", { length: 80 }).notNull(),
  datasetScope: varchar("dataset_scope", { length: 160 }).notNull(),
  analyzedAt: time("analyzed_at"),
  reviewedBy: varchar("reviewed_by", { length: 255 }),
  reviewedAt: time("reviewed_at"),
  suggestedRoute: varchar("suggested_route", { length: 40 }),
  confidence: doublePrecision("confidence"),
  structuredResult: jsonb("structured_result"),
  officialReferenceSnapshot: jsonb("official_reference_snapshot").notNull(),
  observedContentSnapshot: jsonb("observed_content_snapshot").notNull(),
  inputHash: varchar("input_hash", { length: 64 }).notNull(),
  reviewedResult: jsonb("reviewed_result"),
  reviewRound: integer("review_round").notNull().default(1),
  attemptCount: integer("attempt_count").notNull().default(0),
  executionCount: integer("execution_count").notNull().default(0),
  nextAttemptAt: time("next_attempt_at").notNull().defaultNow(),
  leaseToken: uuid("lease_token"),
  leaseExpiresAt: time("lease_expires_at"),
  errorCode: varchar("error_code", { length: 80 }),
  failedAt: time("failed_at"),
  ...demoColumns(),
  createdAt: time("created_at").notNull().defaultNow(),
  updatedAt: time("updated_at").notNull().defaultNow(),
  archivedAt: time("archived_at"),
}, (t) => [
  unique("marjea_analysis_tenant_id_unique").on(t.institutionId, t.id),
  unique("marjea_analysis_tenant_case_id_unique").on(t.institutionId, t.caseId, t.id),
  unique("marjea_analysis_pair_unique").on(t.institutionId, t.officialReferenceId, t.officialReferenceVersionNumber, t.observedContentId, t.datasetScope, t.engineVersion, t.id),
  unique("marjea_analysis_input_unique").on(t.institutionId, t.officialReferenceId, t.observedContentId, t.inputHash, t.engineVersion),
  check("marjea_analysis_status_check", sql`${t.analysisStatus} IN ('queued','processing','pending_human_review','approved','revision_requested','rejected','escalated','failed')`),
  check("marjea_analysis_confidence_check", sql`${t.confidence} IS NULL OR (${t.confidence} >= 0 AND ${t.confidence} <= 1)`),
  check("marjea_analysis_hash_check", sql`${t.inputHash} ~ '^[0-9a-f]{64}$'`),
  check("marjea_analysis_snapshot_check", sql`jsonb_typeof(${t.officialReferenceSnapshot}) = 'object' AND jsonb_typeof(${t.observedContentSnapshot}) = 'object' AND jsonb_typeof(${t.officialReferenceSnapshot}->'contentText') IS NOT DISTINCT FROM 'string' AND jsonb_typeof(${t.observedContentSnapshot}->'contentText') IS NOT DISTINCT FROM 'string'`),
  check("marjea_analysis_result_check", sql`${t.analysisStatus} NOT IN ('pending_human_review','approved','revision_requested','rejected','escalated') OR (${t.structuredResult} IS NOT NULL AND jsonb_typeof(${t.structuredResult}) = 'object' AND ${t.analyzedAt} IS NOT NULL AND ${t.confidence} IS NOT NULL AND ${t.suggestedRoute} IS NOT NULL)`),
  check("marjea_analysis_route_check", sql`${t.suggestedRoute} IS NULL OR ${t.suggestedRoute} IN ('no_material_deviation','human_review','escalation_recommended','insufficient_evidence')`),
  check("marjea_analysis_review_check", sql`(${t.reviewedBy} IS NULL) = (${t.reviewedAt} IS NULL) AND (${t.reviewedBy} IS NULL OR ${t.reviewedBy} <> ${t.requestedBy}) AND (${t.analysisStatus} NOT IN ('approved','rejected') OR (${t.reviewedBy} IS NOT NULL AND ${t.reviewedResult} IS NOT NULL))`),
  check("marjea_analysis_attempt_check", sql`${t.attemptCount} >= 0 AND ${t.reviewRound} >= 1 AND (${t.leaseToken} IS NULL) = (${t.leaseExpiresAt} IS NULL)`),
  check("marjea_analysis_execution_check", sql`${t.executionCount} BETWEEN 0 AND 3`),
  check("marjea_analysis_failed_check", sql`${t.analysisStatus} <> 'failed' OR (${t.failedAt} IS NOT NULL AND ${t.errorCode} IS NOT NULL)`),
  check("marjea_analysis_demo_check", sql`(${t.demoScenarioId} IS NULL AND ${t.demoGeneration} IS NULL) OR (${t.demoScenarioId} IS NOT NULL AND ${t.demoGeneration} IS NOT NULL AND ${t.demoGeneration} >= 1)`),
  foreignKey({ name: "marjea_analysis_version_fk", columns: [t.institutionId, t.officialReferenceId, t.officialReferenceVersionNumber], foreignColumns: [officialReferenceVersions.tenantId, officialReferenceVersions.referenceId, officialReferenceVersions.versionNumber] }),
  foreignKey({ name: "marjea_analysis_observation_fk", columns: [t.institutionId, t.observedContentId], foreignColumns: [observedContent.tenantId, observedContent.id] }),
  foreignKey({ name: "marjea_analysis_case_pair_fk", columns: [t.institutionId, t.caseId, t.officialReferenceId, t.observedContentId], foreignColumns: [cases.tenantId, cases.id, cases.referenceId, cases.observedContentId] }),
  foreignKey({ name: "marjea_analysis_requester_fk", columns: [t.institutionId, t.requestedBy], foreignColumns: [institutionMemberships.tenantId, institutionMemberships.clerkUserId] }),
  foreignKey({ name: "marjea_analysis_reviewer_fk", columns: [t.institutionId, t.reviewedBy], foreignColumns: [institutionMemberships.tenantId, institutionMemberships.clerkUserId] }),
  foreignKey({ name: "marjea_analysis_demo_fk", columns: [t.institutionId, t.demoScenarioId], foreignColumns: [demoScenarios.institutionId, demoScenarios.id] }),
  index("marjea_analysis_created_idx").on(t.institutionId, t.analysisStatus, t.createdAt),
  index("marjea_analysis_due_idx").on(t.analysisStatus, t.nextAttemptAt).where(sql`${t.archivedAt} IS NULL`),
  index("marjea_analysis_lease_idx").on(t.leaseExpiresAt).where(sql`${t.analysisStatus} = 'processing'`),
  index("marjea_analysis_pair_idx").on(t.institutionId, t.officialReferenceId, t.observedContentId, t.engineVersion),
  index("marjea_analysis_demo_idx").on(t.institutionId, t.demoScenarioId, t.demoGeneration),
  policy("marjea_analysis_tenant_policy"),
]).enableRLS();

export const referenceObservations = pgTable("marjea_reference_observations", {
  id: uuid("id").primaryKey().defaultRandom(),
  institutionId: uuid("institution_id").notNull().references(() => institutions.id),
  officialReferenceId: uuid("official_reference_id").notNull(),
  officialReferenceVersionNumber: integer("official_reference_version_number").notNull(),
  observedContentId: uuid("observed_content_id").notNull(),
  datasetScope: varchar("dataset_scope", { length: 160 }).notNull(),
  eligibilityStatus: varchar("eligibility_status", { length: 30 }).notNull().default("eligible"),
  linkedBy: varchar("linked_by", { length: 255 }).notNull(),
  linkedAt: time("linked_at").notNull().defaultNow(),
  excludedBy: varchar("excluded_by", { length: 255 }),
  excludedAt: time("excluded_at"),
  exclusionReason: text("exclusion_reason"),
  ...demoColumns(),
}, (t) => [
  unique("marjea_ref_observation_scope_unique").on(t.institutionId, t.officialReferenceId, t.officialReferenceVersionNumber, t.observedContentId, t.datasetScope),
  check("marjea_ref_observation_eligibility_check", sql`${t.eligibilityStatus} IN ('eligible','excluded') AND (${t.eligibilityStatus} <> 'excluded' OR (${t.excludedBy} IS NOT NULL AND ${t.excludedAt} IS NOT NULL AND ${t.exclusionReason} IS NOT NULL AND length(trim(${t.exclusionReason})) > 0))`),
  check("marjea_ref_observation_demo_check", sql`(${t.demoScenarioId} IS NULL AND ${t.demoGeneration} IS NULL) OR (${t.demoScenarioId} IS NOT NULL AND ${t.demoGeneration} IS NOT NULL AND ${t.demoGeneration} >= 1)`),
  foreignKey({ name: "marjea_ref_observation_version_fk", columns: [t.institutionId, t.officialReferenceId, t.officialReferenceVersionNumber], foreignColumns: [officialReferenceVersions.tenantId, officialReferenceVersions.referenceId, officialReferenceVersions.versionNumber] }),
  foreignKey({ name: "marjea_ref_observation_content_fk", columns: [t.institutionId, t.observedContentId], foreignColumns: [observedContent.tenantId, observedContent.id] }),
  foreignKey({ name: "marjea_ref_observation_linker_fk", columns: [t.institutionId, t.linkedBy], foreignColumns: [institutionMemberships.tenantId, institutionMemberships.clerkUserId] }),
  foreignKey({ name: "marjea_ref_observation_excluder_fk", columns: [t.institutionId, t.excludedBy], foreignColumns: [institutionMemberships.tenantId, institutionMemberships.clerkUserId] }),
  foreignKey({ name: "marjea_ref_observation_demo_fk", columns: [t.institutionId, t.demoScenarioId], foreignColumns: [demoScenarios.institutionId, demoScenarios.id] }),
  index("marjea_ref_observation_coverage_idx").on(t.institutionId, t.officialReferenceId, t.officialReferenceVersionNumber, t.datasetScope, t.eligibilityStatus),
  index("marjea_ref_observation_demo_idx").on(t.institutionId, t.demoScenarioId, t.demoGeneration),
  policy("marjea_ref_observation_tenant_policy"),
]).enableRLS();

export const firstObservedDeviations = pgTable("marjea_first_observed_deviations", {
  id: uuid("id").primaryKey().defaultRandom(),
  institutionId: uuid("institution_id").notNull().references(() => institutions.id),
  officialReferenceId: uuid("official_reference_id").notNull(),
  officialReferenceVersionNumber: integer("official_reference_version_number").notNull(),
  observedContentId: uuid("observed_content_id").notNull(),
  semanticAnalysisId: uuid("semantic_analysis_id").notNull(),
  datasetScope: varchar("dataset_scope", { length: 160 }).notNull(),
  engineVersion: varchar("engine_version", { length: 160 }).notNull(),
  status: varchar("status", { length: 30 }).notNull().default("candidate"),
  observedOrderAt: time("observed_order_at").notNull(),
  coverageSnapshot: jsonb("coverage_snapshot"),
  coverageHash: varchar("coverage_hash", { length: 64 }),
  nominatedBy: varchar("nominated_by", { length: 255 }).notNull(),
  decidedBy: varchar("decided_by", { length: 255 }),
  decidedAt: time("decided_at"),
  decisionReason: text("decision_reason"),
  ...demoColumns(),
  createdAt: time("created_at").notNull().defaultNow(),
  supersededAt: time("superseded_at"),
  archivedAt: time("archived_at"),
}, (t) => [
  check("marjea_deviation_status_check", sql`${t.status} IN ('candidate','confirmed','rejected')`),
  check("marjea_deviation_decision_check", sql`${t.status} = 'candidate' OR (${t.decidedBy} IS NOT NULL AND ${t.decidedAt} IS NOT NULL AND ${t.decisionReason} IS NOT NULL AND length(trim(${t.decisionReason})) > 0)`),
  check("marjea_deviation_coverage_check", sql`${t.status} <> 'confirmed' OR (${t.coverageSnapshot} IS NOT NULL AND jsonb_typeof(${t.coverageSnapshot}) = 'object' AND ${t.coverageHash} IS NOT NULL AND ${t.coverageHash} ~ '^[0-9a-f]{64}$')`),
  check("marjea_deviation_demo_check", sql`(${t.demoScenarioId} IS NULL AND ${t.demoGeneration} IS NULL) OR (${t.demoScenarioId} IS NOT NULL AND ${t.demoGeneration} IS NOT NULL AND ${t.demoGeneration} >= 1)`),
  foreignKey({ name: "marjea_deviation_analysis_pair_fk", columns: [t.institutionId, t.officialReferenceId, t.officialReferenceVersionNumber, t.observedContentId, t.datasetScope, t.engineVersion, t.semanticAnalysisId], foreignColumns: [semanticAnalyses.institutionId, semanticAnalyses.officialReferenceId, semanticAnalyses.officialReferenceVersionNumber, semanticAnalyses.observedContentId, semanticAnalyses.datasetScope, semanticAnalyses.engineVersion, semanticAnalyses.id] }),
  foreignKey({ name: "marjea_deviation_nominator_fk", columns: [t.institutionId, t.nominatedBy], foreignColumns: [institutionMemberships.tenantId, institutionMemberships.clerkUserId] }),
  foreignKey({ name: "marjea_deviation_decider_fk", columns: [t.institutionId, t.decidedBy], foreignColumns: [institutionMemberships.tenantId, institutionMemberships.clerkUserId] }),
  foreignKey({ name: "marjea_deviation_demo_fk", columns: [t.institutionId, t.demoScenarioId], foreignColumns: [demoScenarios.institutionId, demoScenarios.id] }),
  uniqueIndex("marjea_deviation_current_unique").on(t.institutionId, t.officialReferenceId, t.officialReferenceVersionNumber, t.datasetScope, t.engineVersion).where(sql`${t.status} = 'confirmed' AND ${t.supersededAt} IS NULL AND ${t.archivedAt} IS NULL`),
  index("marjea_deviation_order_idx").on(t.institutionId, t.officialReferenceId, t.datasetScope, t.observedOrderAt),
  index("marjea_deviation_demo_idx").on(t.institutionId, t.demoScenarioId, t.demoGeneration),
  policy("marjea_deviation_tenant_policy"),
]).enableRLS();

export const institutionFeatureFlags = pgTable("marjea_institution_feature_flags", {
  institutionId: uuid("institution_id").primaryKey().references(() => institutions.id),
  phase2SemanticAnalysisEnabled: boolean("phase2_semantic_analysis_enabled").notNull().default(false),
  semanticAttemptLimit: integer("semantic_attempt_limit").notNull().default(100),
  semanticAttemptsReserved: integer("semantic_attempts_reserved").notNull().default(0),
  updatedBy: varchar("updated_by", { length: 255 }).notNull(),
  updatedAt: time("updated_at").notNull().defaultNow(),
  changeReason: text("change_reason").notNull(),
}, (t) => [
  check("marjea_flag_semantic_attempt_limit_check", sql`${t.semanticAttemptLimit} BETWEEN 1 AND 100000`),
  check("marjea_flag_semantic_attempts_reserved_check", sql`${t.semanticAttemptsReserved} >= 0`),
  foreignKey({ name: "marjea_flag_updater_fk", columns: [t.institutionId, t.updatedBy], foreignColumns: [institutionMemberships.tenantId, institutionMemberships.clerkUserId] }),
  policy("marjea_flag_tenant_policy"),
]).enableRLS();

